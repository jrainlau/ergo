import AppKit
import ErgoPluginSupport
import Foundation

@MainActor
enum ClipboardReader {
    static let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    static let marker = NSPasteboard.PasteboardType("com.jrainlau.ergo.marker")
    static let jpeg = NSPasteboard.PasteboardType("public.jpeg")
    static let heic = NSPasteboard.PasteboardType("public.heic")

    enum ReadResult {
        case skip
        case touch(String)
        case capture(RawCapture)
    }

    static func read(_ pb: NSPasteboard, ignoredBundleIDs: Set<String>, source: NSRunningApplication?) -> ReadResult {
        let types = pb.types ?? []
        guard !types.isEmpty else { return .skip }
        if types.contains(concealed) || types.contains(transient) || types.contains(autoGenerated) { return .skip }
        if types.contains(marker) {
            let v = pb.string(forType: marker)
            if v == "restore" || v == nil { return .skip }
            return .touch(v!)
        }
        var bundleID = source?.bundleIdentifier
        var appName = source?.localizedName
        if bundleID == Bundle.main.bundleIdentifier { bundleID = nil; appName = nil }
        if let b = bundleID, ignoredBundleIDs.contains(b) { return .skip }

        var raw = RawCapture()
        raw.sourceBundleID = bundleID
        raw.sourceAppName = appName
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            raw.fileURLs = urls
            return .capture(raw)
        }
        raw.string = pb.string(forType: .string)
        raw.rtf = pb.data(forType: .rtf)
        for t in [NSPasteboard.PasteboardType.png, .tiff, jpeg, heic] {
            if types.contains(t), let d = pb.data(forType: t) { raw.imageData = d; break }
        }
        // 表格 / 富文本软件常同时附带图片，此时以文本为准
        if raw.imageData != nil, raw.string != nil, raw.rtf != nil || types.contains(.html) {
            raw.imageData = nil
        }
        if raw.imageData == nil, raw.string == nil, types.contains(.color), let c = NSColor(from: pb) {
            raw.colorHex = hex(c)
        }
        return .capture(raw)
    }

    static func hex(_ c: NSColor) -> String {
        guard let s = c.usingColorSpace(.sRGB) else { return "#000000" }
        return String(format: "#%02X%02X%02X", Int(round(s.redComponent * 255)), Int(round(s.greenComponent * 255)), Int(round(s.blueComponent * 255)))
    }
}

@MainActor
final class ClipboardMonitor {
    private let pasteboard: NSPasteboard
    private let store: ClipboardStore
    private let settings: () -> ClipboardSettings
    private let onChange: () -> Void
    private var timer: Timer?
    private var lastChangeCount: Int
    private var chain: Task<Void, Never>?

    init(pasteboard: NSPasteboard = .general, store: ClipboardStore, settings: @escaping () -> ClipboardSettings, onChange: @escaping () -> Void) {
        self.pasteboard = pasteboard
        self.store = store
        self.settings = settings
        self.onChange = onChange
        lastChangeCount = pasteboard.changeCount
    }

    func start() {
        stop()
        let interval = min(max(settings().pollInterval, 0.25), 1.0)
        let t = Timer(timeInterval: interval, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.tick() }
        }
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    func stop() {
        timer?.invalidate()
        timer = nil
        chain?.cancel()
    }

    func tick() {
        let cc = pasteboard.changeCount
        guard cc != lastChangeCount else { return }
        lastChangeCount = cc
        let s = settings()
        switch ClipboardReader.read(pasteboard, ignoredBundleIDs: Set(s.ignoredBundleIDs), source: NSWorkspace.shared.frontmostApplication) {
        case .skip:
            return
        case .touch(let id):
            try? store.touch(id: id)
            onChange()
        case .capture(let raw):
            let store = self.store
            let filter = s.filter
            let previous = chain
            chain = Task { [weak self] in
                await previous?.value
                let stored = await Task.detached(priority: .utility) { () -> Bool in
                    guard let c = ClipboardProcessor.classify(raw, filter: filter) else { return false }
                    if (try? store.touch(hash: c.hash)) == true { return true }
                    let item = ClipboardProcessor.makeItem(from: c, blobsDir: store.blobsDir, thumbsDir: store.thumbsDir, filter: filter)
                    do { try store.insert(item) } catch { return false }
                    return true
                }.value
                if stored { self?.onChange() }
            }
        }
    }
}
